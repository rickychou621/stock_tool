import { expect, it } from 'vitest'
import { daysSinceTaipei, formatTaipeiTime } from './time'

it.each([
  ['2026-10-22T05:58:53', '2026/10/22 13:58'],
  ['2026-10-22T05:58:53Z', '2026/10/22 13:58'],
  ['2026-10-22T13:58:53+08:00', '2026/10/22 13:58'],
  ['2026-10-22T05:58:53-04:00', '2026/10/22 17:58'],
  ['2026-10-22T17:00:00', '2026/10/23 01:00'],
  ['2026-10-22T16:00:00Z', '2026/10/23 00:00'],
  [null, '—'], [undefined, '—'], ['', '—'], ['   ', '—'], ['invalid', '—'],
])('格式化 %s 為台北時間', (value, expected) => {
  expect(formatTaipeiTime(value)).toBe(expected)
})

it.each([
  ['2026-10-22T15:59:00', '2026-10-22T16:01:00Z', 1],
  ['2026-10-22T16:00:00Z', '2026-10-23T15:59:00Z', 0],
  ['2026-09-30T23:00:00+08:00', '2026-10-02T00:00:00+08:00', 2],
  ['2025-12-31T15:00:00Z', '2026-01-01T16:00:00Z', 2],
  ['2026-10-24T00:00:00+08:00', '2026-10-23T00:00:00+08:00', -1],
])('依台北日期計算過期天數 %s', (value, now, expected) => {
  expect(daysSinceTaipei(value, new Date(now))).toBe(expected)
})

it('無效日期沒有可計算的過期天數', () => {
  expect(daysSinceTaipei('invalid')).toBeNaN()
})
